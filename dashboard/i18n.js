function getLanguage() {
  return localStorage.getItem('yaa_lang') || 'en';
}

function setLanguage(lang) {
  localStorage.setItem('yaa_lang', lang);
}

function t(key, vars) {
  const parts = key.split('.');
  let node = LOCALES[getLanguage()];
  for (const part of parts) {
    node = node?.[part];
    if (node === undefined) break;
  }
  if (typeof node !== 'string') return key;
  if (!vars) return node;
  return node.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

function applyTranslations(root = document) {
  Array.from(root.querySelectorAll('[data-i18n]')).forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  // Only for the rare string that must keep an inline tag (e.g. "Create a
  // <strong>Desktop app</strong>..."). The translated value is still fully
  // author-controlled (LOCALES, not user input), so this is not an XSS risk.
  Array.from(root.querySelectorAll('[data-i18n-html]')).forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  Array.from(root.querySelectorAll('[data-i18n-placeholder]')).forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  Array.from(root.querySelectorAll('[data-i18n-title]')).forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  Array.from(root.querySelectorAll('[data-i18n-aria-label]')).forEach(el => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
}

document.documentElement.lang = getLanguage();
applyTranslations();
